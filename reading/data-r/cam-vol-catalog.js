export const VOL_CONFIG = {
  minVol: 1,
  maxVol: 8,
  testsPerVol: 10,
  passagesPerTest: 3
};

export function getCamTests(camNum) {
  try {
    const num = Number(camNum);
    const found = CAM_DATA.find(item => item.cam === num);
    return found && Array.isArray(found.tests) ? found.tests : [];
  } catch (e) {
    return [];
  }
}

export function getAvailableCamNumbers() {
  try {
    return CAM_DATA.map(item => item.cam);
  } catch (e) {
    return [21, 20, 19, 18, 17];
  }
}

export function getAvailableVolNumbers() {
  try {
    const list = [];
    for (let v = VOL_CONFIG.maxVol; v >= VOL_CONFIG.minVol; v--) {
      list.push(v);
    }
    return list;
  } catch (e) {
    return [8, 7, 6, 5, 4, 3, 2, 1];
  }
}
